#!/usr/bin/env node

/**
 * ============================================================================
 * API Wrapper Generator
 * ============================================================================
 *
 * Reads the OpenAPI spec JSON and generates:
 *   1. Typed fetch wrapper functions per endpoint
 *   2. queryOptions() factories (for GET endpoints)
 *   3. useQuery / useMutation hooks
 *
 * Each Swagger tag becomes one file: src/api/hooks/{tag}.api.ts
 *
 * Usage:
 *   node scripts/generate-api-hooks.js [path-to-openapi.json]
 *
 * This script is idempotent — safe to re-run on every change.
 * ============================================================================
 */

const fs = require("fs");
const path = require("path");

// ── Config ──────────────────────────────────────────────────────────────

const OPENAPI_PATH =
  process.argv[2] ||
  path.resolve(__dirname, "..", "openapi.json");

// Generated hooks live in the shared core package so web + mobile can import
// them from `@monorepo/core/api`. Paths below are relative to apps/api/scripts.
const OUTPUT_DIR = path.resolve(
  __dirname,
  "..",
  "..",
  "..",
  "packages",
  "core",
  "src",
  "api",
  "hooks",
);
const MODELS_IMPORT_PATH = "../generated";
const CLIENT_IMPORT_PATH = "../client";

const GENERATED_HEADER = `/* ==========================================================================
 * THIS FILE IS AUTO-GENERATED — DO NOT EDIT MANUALLY.
 *
 * Generated by: scripts/generate-api-hooks.js
 * Source:       OpenAPI spec (openapi.json)
 * ========================================================================== */

`;

// ── Main ────────────────────────────────────────────────────────────────

function main() {
  if (!fs.existsSync(OPENAPI_PATH)) {
    console.error(`❌ OpenAPI spec not found at: ${OPENAPI_PATH}`);
    console.error(`   Run the server and download it first.`);
    process.exit(1);
  }

  const spec = JSON.parse(fs.readFileSync(OPENAPI_PATH, "utf-8"));
  const operations = extractOperations(spec);
  const grouped = groupByTag(operations);

  // Ensure output dir
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });

  // Collect all generated filenames so we can write an index
  const generatedFiles = [];

  for (const [tag, ops] of Object.entries(grouped)) {
    const fileName = `${kebabCase(tag)}.api.ts`;
    const filePath = path.join(OUTPUT_DIR, fileName);
    const content = generateFileContent(tag, ops, spec);
    fs.writeFileSync(filePath, content, "utf-8");
    generatedFiles.push({ tag, fileName });
    console.log(`  ✅ ${fileName} (${ops.length} endpoints)`);
  }

  // Write barrel index
  const indexContent =
    GENERATED_HEADER +
    generatedFiles
      .map((f) => `export * from "./${f.fileName.replace(".ts", "")}";`)
      .join("\n") +
    "\n";
  fs.writeFileSync(path.join(OUTPUT_DIR, "index.ts"), indexContent, "utf-8");
  console.log(`  ✅ index.ts (barrel)`);

  console.log(
    `\n🎉 Generated ${generatedFiles.length} API hook files with ${operations.length} total endpoints.\n`,
  );
}

// ── Extract operations from the OpenAPI spec ────────────────────────────

function extractOperations(spec) {
  const operations = [];

  for (const [pathStr, pathItem] of Object.entries(spec.paths || {})) {
    for (const method of ["get", "post", "put", "patch", "delete"]) {
      const op = pathItem[method];
      if (!op) continue;

      const tag = op.tags?.[0] || "Default";
      const operationId = op.operationId;

      // Extract path params and query params
      const pathParams = [];
      const queryParams = [];
      let querySchemaRef = null;

      for (const param of op.parameters || []) {
        if (param.in === "path") {
          pathParams.push({
            name: param.name,
            type: mapSchemaType(param.schema),
            required: param.required !== false,
          });
        } else if (param.in === "query") {
          queryParams.push({
            name: param.name,
            type: mapSchemaType(param.schema),
            required: param.required === true,
            description: param.description,
          });
        }
      }

      // Extract request body schema ref
      let bodyRef = null;
      let bodySchemaName = null;
      let isFormData = false;
      let fileUploadFields = []; // e.g. [{name:"image", multiple:false}]
      const requestBody = op.requestBody;
      if (requestBody?.content) {
        if (requestBody.content["multipart/form-data"]) {
          isFormData = true;
          const schema = requestBody.content["multipart/form-data"].schema;
          bodyRef = schema?.$ref;
          bodySchemaName = bodyRef ? refToName(bodyRef) : null;

          // Detect inline file upload fields (format: "binary")
          if (!bodyRef && schema?.type === "object" && schema.properties) {
            for (const [fieldName, fieldSchema] of Object.entries(schema.properties)) {
              if (fieldSchema.format === "binary") {
                fileUploadFields.push({ name: fieldName, multiple: false });
              } else if (
                fieldSchema.type === "array" &&
                fieldSchema.items?.format === "binary"
              ) {
                fileUploadFields.push({ name: fieldName, multiple: true });
              }
            }
          }
        } else if (requestBody.content["application/json"]) {
          const schema = requestBody.content["application/json"].schema;
          bodyRef = schema?.$ref;
          bodySchemaName = bodyRef ? refToName(bodyRef) : null;
        }
      }

      // Extract response type (best effort)
      let responseType = "void";
      const responses = op.responses;
      if (responses) {
        const successResponse = responses["200"] || responses["201"];
        if (successResponse?.content?.["application/json"]?.schema) {
          const schema = successResponse.content["application/json"].schema;
          responseType = resolveSchemaType(schema);
        }
      }

      operations.push({
        tag,
        operationId,
        method: method.toUpperCase(),
        path: pathStr,
        pathParams,
        queryParams,
        bodySchemaName,
        isFormData,
        fileUploadFields,
        responseType,
        summary: op.summary || "",
        description: op.description || "",
      });
    }
  }

  return operations;
}

// ── Group operations by tag ─────────────────────────────────────────────

function groupByTag(operations) {
  const groups = {};
  for (const op of operations) {
    if (!groups[op.tag]) groups[op.tag] = [];
    groups[op.tag].push(op);
  }
  return groups;
}

// ── Generate file content for one tag ───────────────────────────────────

function generateFileContent(tag, operations, spec) {
  const imports = new Set();
  const modelImports = new Set();

  // We always need apiRequest
  imports.add("apiRequest");

  // Collect model types that we need to import
  for (const op of operations) {
    if (op.bodySchemaName) {
      modelImports.add(op.bodySchemaName);
    }
    // Also import response types that reference a model
    if (op.responseType && op.responseType !== "any" && op.responseType !== "void") {
      // Strip array suffix to get the base type name
      const baseType = op.responseType.replace(/\[\]$/, "");
      if (/^[A-Z]/.test(baseType)) {
        modelImports.add(baseType);
      }
    }
  }

  const sections = [];

  for (const op of operations) {
    sections.push(generateOperation(op, modelImports));
  }

  // Build imports block
  let code = GENERATED_HEADER;

  code += `import { ${[...imports].join(", ")} } from "${CLIENT_IMPORT_PATH}";\n`;

  if (modelImports.size > 0) {
    code += `import type { ${[...modelImports].sort().join(", ")} } from "${MODELS_IMPORT_PATH}";\n`;
  }

  code += "\n";
  code += sections.join("\n");

  return code;
}

// ── Generate one operation (fetch fn + queryOptions + hook) ─────────────

function generateOperation(op) {
  const fnName = operationIdToFnName(op.operationId);
  const isQuery = op.method === "GET";
  const isMutation = !isQuery;

  // Build function parameters
  const fnParams = [];
  const fnParamTypes = [];

  // Path params come first
  for (const p of op.pathParams) {
    fnParams.push(p.name);
    fnParamTypes.push(`${p.name}: ${p.type}`);
  }

  // Query params → inline object type
  if (op.queryParams.length > 0) {
    const qType = buildQueryParamsType(op.queryParams);
    const allOptional = op.queryParams.every((p) => !p.required);
    fnParams.push("query");
    fnParamTypes.push(`query${allOptional ? "?" : ""}: ${qType}`);
  }

  // Body param
  if (op.bodySchemaName) {
    fnParams.push("body");
    fnParamTypes.push(`body: ${op.bodySchemaName}`);
  }

  // File upload params (multipart/form-data without a DTO ref)
  const hasFileUpload = op.fileUploadFields && op.fileUploadFields.length > 0;
  if (hasFileUpload && !op.bodySchemaName) {
    for (const field of op.fileUploadFields) {
      fnParams.push(field.name);
      if (field.multiple) {
        fnParamTypes.push(`${field.name}: File[] | Blob[]`);
      } else {
        fnParamTypes.push(`${field.name}: File | Blob`);
      }
    }
  }

  // Build the path with interpolation
  const interpolatedPath = op.path.replace(
    /\{(\w+)\}/g,
    (_, name) => `\${${name}}`,
  );

  const lines = [];

  // ── JSDoc ──
  if (op.summary || op.description) {
    lines.push("/**");
    if (op.summary) lines.push(` * ${op.summary}`);
    if (op.description && op.description !== op.summary)
      lines.push(` * ${op.description}`);
    lines.push(` * \`${op.method} ${op.path}\``);
    lines.push(" */");
  }

  // ── Fetch function ──
  const returnType = op.responseType && op.responseType !== "any" ? op.responseType : "any";

  if (hasFileUpload && !op.bodySchemaName) {
    // File upload endpoint → build FormData in the function body
    lines.push(
      `export async function ${fnName}(${fnParamTypes.join(", ")}): Promise<${returnType}> {`,
    );
    lines.push(`  const formData = new FormData();`);
    for (const field of op.fileUploadFields) {
      if (field.multiple) {
        lines.push(`  for (const f of ${field.name}) {`);
        lines.push(`    formData.append("${field.name}", f);`);
        lines.push(`  }`);
      } else {
        lines.push(`  formData.append("${field.name}", ${field.name});`);
      }
    }
    lines.push(`  return apiRequest<${returnType}>({`);
    lines.push(`    method: "${op.method}",`);
    lines.push(`    path: \`${interpolatedPath}\`,`);
    if (op.queryParams.length > 0) {
      lines.push(`    query: query as unknown as Record<string, unknown>,`);
    }
    lines.push(`    body: formData,`);
    lines.push(`    formData: true,`);
    lines.push(`  });`);
    lines.push(`}`);
    lines.push("");
  } else {
    // Normal endpoint (JSON body or no body)
    lines.push(
      `export async function ${fnName}(${fnParamTypes.join(", ")}): Promise<${returnType}> {`,
    );
    lines.push(`  return apiRequest<${returnType}>({`);
    lines.push(`    method: "${op.method}",`);
    lines.push(`    path: \`${interpolatedPath}\`,`);

    if (op.queryParams.length > 0) {
      lines.push(
        `    query: query as unknown as Record<string, unknown>,`,
      );
    }

    if (op.bodySchemaName && !op.isFormData) {
      lines.push(`    body,`);
    }
    if (op.bodySchemaName && op.isFormData) {
      lines.push(`    body,`);
      lines.push(`    formData: true,`);
    }

    lines.push(`  });`);
    lines.push(`}`);
    lines.push("");
  }

  // ── Query Key factory ──
  const keyBase = camelToKebab(fnName);
  const keyParts = [`"${keyBase}"`];
  for (const p of op.pathParams) {
    keyParts.push(p.name);
  }

  if (isQuery) {
    // queryKey function
    const keyFnParams = [...fnParamTypes];
    // Make query optional for key too
    lines.push(
      `export function ${fnName}Key(${keyFnParams.join(", ")}) {`,
    );
    const keyArr = [...keyParts];
    if (op.queryParams.length > 0) keyArr.push("query");
    lines.push(`  return [${keyArr.join(", ")}] as const;`);
    lines.push(`}`);
    lines.push("");

    // queryOptions
    lines.push(
      `export function ${fnName}Options(${fnParamTypes.join(", ")}) {`,
    );
    lines.push(`  return {`);
    lines.push(`    queryKey: ${fnName}Key(${fnParams.join(", ")}),`);
    lines.push(`    queryFn: () => ${fnName}(${fnParams.join(", ")}),`);
    lines.push(`  };`);
    lines.push(`}`);
    lines.push("");
  }

  if (isMutation) {
    // mutationOptions helper
    // For mutations, the "variables" type is the full arg set
    const mutVarFields = [];
    for (const p of op.pathParams) {
      mutVarFields.push(`${p.name}: ${p.type}`);
    }
    if (op.bodySchemaName) {
      mutVarFields.push(`body: ${op.bodySchemaName}`);
    }
    // Include file upload fields in mutation variables
    if (hasFileUpload && !op.bodySchemaName) {
      for (const field of op.fileUploadFields) {
        if (field.multiple) {
          mutVarFields.push(`${field.name}: File[] | Blob[]`);
        } else {
          mutVarFields.push(`${field.name}: File | Blob`);
        }
      }
    }

    const mutVarType =
      mutVarFields.length > 0
        ? `{ ${mutVarFields.join("; ")} }`
        : "void";

    lines.push(`export function ${fnName}Options() {`);
    lines.push(`  return {`);

    if (mutVarFields.length > 0) {
      const destructured = [];
      for (const p of op.pathParams) destructured.push(p.name);
      if (op.bodySchemaName) destructured.push("body");
      if (hasFileUpload && !op.bodySchemaName) {
        for (const field of op.fileUploadFields) destructured.push(field.name);
      }
      lines.push(
        `    mutationFn: ({ ${destructured.join(", ")} }: ${mutVarType}) => ${fnName}(${fnParams.filter((p) => p !== "query").join(", ")}),`,
      );
    } else {
      lines.push(`    mutationFn: () => ${fnName}(),`);
    }

    // Invalidation hint
    lines.push(`  };`);
    lines.push(`}`);
    lines.push("");
  }

  return lines.join("\n");
}

// ── Build inline query params type ──────────────────────────────────────

function buildQueryParamsType(params) {
  const fields = params.map((p) => {
    const opt = p.required ? "" : "?";
    return `${p.name}${opt}: ${p.type}`;
  });
  return `{ ${fields.join("; ")} }`;
}

// ── Schema helpers ──────────────────────────────────────────────────────

function mapSchemaType(schema) {
  if (!schema) return "any";
  if (schema.$ref) return refToName(schema.$ref);
  if (schema.enum) {
    return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  }
  switch (schema.type) {
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${mapSchemaType(schema.items)}[]`;
    case "object":
      return "Record<string, any>";
    default:
      return "string";
  }
}

function resolveSchemaType(schema) {
  if (!schema) return "any";
  if (schema.$ref) return refToName(schema.$ref);
  if (schema.type === "array") {
    return `${resolveSchemaType(schema.items)}[]`;
  }
  return mapSchemaType(schema);
}

function refToName(ref) {
  return ref.split("/").pop();
}

// ── Naming helpers ──────────────────────────────────────────────────────

/**
 * Converts operationId like "ProductsController_findAll"
 * into a clean function name like "productsFindAll"
 */
function operationIdToFnName(operationId) {
  if (!operationId) return "unknownOperation";

  // "ProductsController_findAll" → ["Products", "findAll"]
  const parts = operationId.split("_");
  if (parts.length >= 2) {
    const controller = parts[0]
      .replace(/Controller$/i, "")
      .replace(/^./, (c) => c.toLowerCase());
    const method = parts.slice(1).join("_");
    return `${controller}${method.charAt(0).toUpperCase()}${method.slice(1)}`;
  }

  return operationId.replace(/^./, (c) => c.toLowerCase());
}

function camelToKebab(str) {
  return str
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
}

function kebabCase(str) {
  return str
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase();
}

// ── Run ─────────────────────────────────────────────────────────────────

console.log("\n🔧 Generating API hooks from OpenAPI spec...\n");
main();
